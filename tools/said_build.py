# 古人说：本站自建句库。读 said_src.txt（标签|原句|作者），在 build/corpus.json 中核对原文，输出 app/site/said.json
import json, re, collections, os
R = os.path.dirname(os.path.abspath(__file__)) + '/..'
C = json.load(open(R + '/build/corpus.json'))
M = json.load(open(R + '/build/meta_raw.json'))
cdyn = {m['code']: m['dyn'] for m in M['colls']}
BIG = {'tang', 'songshi', 'songci', 'yuanqu', 'jiuti', 'jinyuan', 'mingshi', 'qingshi', 'buyi', 'xiantang'}
N = re.compile(r'[^\u3400-\u9fff]')
ANON = {'佚名', '无名氏', '阙名', '不详'}
by_a = collections.defaultdict(list)
for r in C: by_a[r['a']].append(r)
def body(r): return N.sub('', ''.join(r['p'])).replace('茍', '苟')
def find(q, a):
    k = N.sub('', q)
    pools = [by_a.get(a, [])]
    if a in ANON or not pools[0]: pools.append(C)
    for pool in pools:
        hits = [r for r in pool if k in body(r)]
        if hits:
            hits.sort(key=lambda r: (r['c'] in BIG, r['a'] in ANON and a not in ANON, r['i']))
            return hits[0], q
    # 异文：同作者篇目里逐个短句比对，每句容忍 1～2 字差异，返回本站原文版本
    if a in ANON: return None
    cl = [c for c in re.split(r'[^\u3400-\u9fff]+', q) if c]
    def fz(b, c):
        n = len(c); tol = 2 if n >= 7 else (1 if n >= 4 else 0)
        best = None
        for i in range(len(b) - n + 1):
            d = sum(1 for x, y in zip(b[i:i + n], c) if x != y)
            if d <= tol and (best is None or d < best[0]): best = (d, b[i:i + n])
            if best and best[0] == 0: break
        return best
    best = None
    for r in sorted(by_a.get(a, []), key=lambda r: (r['c'] in BIG, r['i'])):
        b = body(r); res = [fz(b, c) for c in cl]
        if all(res):
            d = sum(x[0] for x in res)
            if d <= max(1, len(k) // 7) and (best is None or d < best[0]): best = (d, r, res)
    if not best: return None
    t = q
    for c, x in zip(cl, best[2]): t = t.replace(c, x[1], 1)
    return best[1], t
out = []; miss = []; seen = set()
for ln in open(os.path.dirname(os.path.abspath(__file__)) + '/said_src.txt', encoding='utf-8'):
    ln = ln.strip()
    if not ln or ln.startswith('#'): continue
    tags, q, a = ln.split('|')
    if (q, a) in seen: continue
    seen.add((q, a))
    f = find(q, a)
    if not f: miss.append(ln); continue
    r, q2 = f
    if q2 != q: print('FIX', q, '->', q2)
    out.append([q2, r['a'], r['t'], r.get('d') or cdyn[r['c']], r['i'], tags.split(',')])
